#!/usr/bin/env node
/**
 * Generates src/generated/skillCatalog6e.ts from Hero Designer's Main6E.hdt template.
 *
 * The template is the canonical source for skill XMLIDs, display names and characteristic
 * bases; the HDC writer uses it to emit Hero Designer/Foundry-compatible new skills.
 *
 * Usage: node scripts/generate-skill-catalog.mjs [path/to/Main6E.hdt]
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { XMLParser } from 'fast-xml-parser';

const here = dirname(fileURLToPath(import.meta.url));
const templatePath =
  process.argv[2] ?? resolve(here, '../../../java/Hero Designer Source Code/template/Main6E.hdt');
const outPath = resolve(here, '../src/generated/skillCatalog6e.ts');

const parser = new XMLParser({
  ignoreAttributes: false,
  attributeNamePrefix: '',
  preserveOrder: true,
  parseAttributeValue: false,
});
const tree = parser.parse(readFileSync(templatePath, 'utf8'));

const children = (node) => {
  const key = Object.keys(node).find((k) => k !== ':@');
  return key ? node[key] : [];
};
const tagOf = (node) => Object.keys(node).find((k) => k !== ':@');
const attrsOf = (node) => node[':@'] ?? {};
const num = (value) => (value === undefined || value === '' ? undefined : Number(value));

const template = tree.find((n) => tagOf(n) === 'TEMPLATE');
const sectionOf = (name) => children(template).find((n) => tagOf(n) === name);

const skills = [];
for (const node of children(sectionOf('SKILLS'))) {
  const tag = tagOf(node);
  if (!tag || tag === '#text') continue;
  const attrs = attrsOf(node);
  const choices = children(node)
    .filter((n) => tagOf(n) === 'CHARACTERISTIC_CHOICE')
    .flatMap((n) => children(n).filter((i) => tagOf(i) === 'ITEM'))
    .map((i) => {
      const a = attrsOf(i);
      return {
        characteristic: a.CHARACTERISTIC,
        baseCost: num(a.BASECOST) ?? 0,
        lvlCost: num(a.LVLCOST) ?? 0,
        lvlVal: num(a.LVLVAL) ?? 1,
      };
    });
  skills.push({
    xmlId: attrs.XMLID ?? tag,
    display: attrs.DISPLAY ?? tag,
    inputLabel: attrs.INPUTLABEL,
    familiarityCost: num(attrs.FAMILIARITYCOST),
    baseCost: num(attrs.BASECOST),
    lvlCost: num(attrs.LVLCOST),
    characteristicChoices: choices.length ? choices : undefined,
  });
}

const enhancers = children(sectionOf('SKILL_ENHANCERS'))
  .filter((n) => tagOf(n) === 'ENHANCER')
  .map((n) => {
    const a = attrsOf(n);
    return { xmlId: a.XMLID, display: a.DISPLAY, baseCost: num(a.BASECOST) ?? 3 };
  });

const strip = (obj) => JSON.parse(JSON.stringify(obj));
const banner = `/**
 * GENERATED by scripts/generate-skill-catalog.mjs from Hero Designer's Main6E.hdt.
 * Do not edit by hand; re-run the generator instead.
 */
`;

const body = `${banner}
export interface SkillCatalogChoice {
  characteristic: string;
  baseCost: number;
  lvlCost: number;
  lvlVal: number;
}

export interface SkillCatalogEntry {
  xmlId: string;
  display: string;
  inputLabel?: string;
  familiarityCost?: number;
  baseCost?: number;
  lvlCost?: number;
  characteristicChoices?: SkillCatalogChoice[];
}

export interface SkillEnhancerCatalogEntry {
  xmlId: string;
  display: string;
  baseCost: number;
}

export const SKILL_CATALOG_6E: SkillCatalogEntry[] = ${JSON.stringify(strip(skills), null, 2)};

export const SKILL_ENHANCER_CATALOG_6E: SkillEnhancerCatalogEntry[] = ${JSON.stringify(strip(enhancers), null, 2)};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body);
console.log(`Wrote ${skills.length} skills and ${enhancers.length} enhancers to ${outPath}`);
